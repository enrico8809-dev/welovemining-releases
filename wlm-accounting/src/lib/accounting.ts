export type AcctType = "asset" | "liability" | "equity" | "income" | "expense";

export interface Account {
  id: string;
  name: string;
  type: AcctType;
  bank?: boolean;
}

export interface Txn {
  id: string;
  date: string; // ISO yyyy-mm-dd
  desc: string;
  amount: number; // always positive; debit/credit determine direction
  debit: string; // account id
  credit: string; // account id
  recipe: string; // recipe id, for display/audit purposes
  /** Set when the entry was generated by an invoice, so it can't be hand-edited. */
  sourceDoc?: string;
  /** Set on every change; drives last-write-wins during cloud sync. */
  updatedAt?: number;
  /** Set instead of removing the record, so the deletion reaches other devices. */
  deletedAt?: number;
}

