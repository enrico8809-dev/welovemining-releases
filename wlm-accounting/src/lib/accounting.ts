export interface MonthPoint {
  key: string; // "2026-03"
  label: string; // "Mar"
  income: number;
  expenses: number;
  net: number;
}

/**
 * Money in/out per calendar month. "In" and "out" are judged by which side the
 * bank account sits on, so an invoice settlement counts as cash in without
 * being counted as income twice.
 */
export function monthlyCashFlow(txns: Txn[], months = 6, now = new Date()): MonthPoint[] {
  const points: MonthPoint[] = [];
  const index = new Map<string, MonthPoint>();

  for (let i = months - 1; i >= 0; i--) {
    const d = new Date(now.getFullYear(), now.getMonth() - i, 1);
    const key = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}`;
    const point: MonthPoint = { key, label: MONTHS[d.getMonth()], income: 0, expenses: 0, net: 0 };
    points.push(point);
    index.set(key, point);
  }

  for (const t of txns) {
    const point = index.get(t.date.slice(0, 7));
    if (!point) continue;
    if (t.debit === "bank") point.income += t.amount;
    else if (t.credit === "bank") point.expenses += t.amount;
  }

  for (const p of points) p.net = p.income - p.expenses;
  return points;
}

/**
 * Running bank balance over the last N transactions affecting the bank,
 * oldest first — the series behind the dashboard sparkline.
 */
export function bankBalanceSeries(txns: Txn[], openingBank: number, points = 24): number[] {
  const bankTxns = txns
    .filter((t) => t.debit === "bank" || t.credit === "bank")
    .sort((a, b) => (a.date < b.date ? -1 : a.date > b.date ? 1 : a.id.localeCompare(b.id)));

  const series: number[] = [openingBank];
  let running = openingBank;
  for (const t of bankTxns) {
    running += t.debit === "bank" ? t.amount : -t.amount;
    series.push(running);
  }
  return series.length <= points ? series : series.slice(series.length - points);
}

export function txnsForAccount(txns: Txn[], accountId: string): Txn[] {
  return txns.filter((t) => t.debit === accountId || t.credit === accountId);
}

export function filterByPeriod(txns: Txn[], period: Period): Txn[] {
  return txns.filter((t) => inPeriod(t.date, period));
}

/** Free-text search across description, date and the accounts involved. */
export function searchTxns(txns: Txn[], accounts: Account[], query: string): Txn[] {
  const q = query.trim().toLowerCase();
  if (!q) return txns;
  return txns.filter((t) => {
    const names = `${accountName(accounts, t.debit)} ${accountName(accounts, t.credit)}`;
    return (
      t.desc.toLowerCase().includes(q) ||
      t.date.includes(q) ||
      names.toLowerCase().includes(q) ||
      String(t.amount).includes(q)
    );
  });
}

export function sortByDateDesc(txns: Txn[]): Txn[] {
  return [...txns].sort((a, b) =>
    a.date < b.date ? 1 : a.date > b.date ? -1 : b.id.localeCompare(a.id)
  );
}

/** The non-bank side of an entry — what the ledger row actually shows. */
export function counterAccountId(t: Txn): string {
  return t.debit === "bank" ? t.credit : t.debit;
}

export function isMoneyIn(t: Txn): boolean {
  return t.debit === "bank";
}

/** Guards against a date the user typed by hand landing in the far future. */
export function isReasonableDate(iso: string): boolean {
  const d = parseISO(iso);
  if (!d) return false;
  const year = d.getFullYear();
  return year >= 2000 && year <= new Date().getFullYear() + 1;
}
