/**
 * Balance engine: debit adds, credit subtracts.
 *
 * The opening bank balance is posted as a real double entry — Dr Bank /
 * Cr Owner Contribution — rather than dropped into the bank on its own. Money
 * already in the business at the start is the owner's capital, and seeding it
 * one-sided would leave the trial balance permanently out by that amount.
 *
 * Income and liability/equity accounts naturally carry credit balances, which show
 * up as negative numbers here — flip the sign when displaying them. Asset/expense
 * accounts naturally carry debit (positive) balances.
 */
export function computeBalances(
  accounts: Account[],
  txns: Txn[],
  openingBank: number
): Record<string, number> {
  const b: Record<string, number> = {};
  accounts.forEach((a) => (b[a.id] = 0));

  if (openingBank !== 0) {
    b.bank += openingBank;
    b.owner_contrib -= openingBank;
  }

  for (const t of txns) {
    b[t.debit] = (b[t.debit] ?? 0) + t.amount;
    b[t.credit] = (b[t.credit] ?? 0) - t.amount;
  }
  return b;
}

/** Display balance: flips sign for accounts that naturally carry a credit balance. */
export function displayBalance(account: Account, raw: number): number {
  return account.type === "income" ||
    account.type === "liability" ||
    account.type === "equity"
    ? -raw
    : raw;
}

export interface ProfitAndLoss {
  income: number;
  expenses: number;
  net: number;
  incomeLines: { account: Account; amount: number }[];
  expenseLines: { account: Account; amount: number }[];
}

export function computeProfitAndLoss(
  accounts: Account[],
  balances: Record<string, number>
): ProfitAndLoss {
  let income = 0;
  let expenses = 0;
  const incomeLines: { account: Account; amount: number }[] = [];
  const expenseLines: { account: Account; amount: number }[] = [];

  for (const a of accounts) {
    const raw = balances[a.id] ?? 0;
    if (a.type === "income") {
      const v = -raw;
      income += v;
      if (v !== 0) incomeLines.push({ account: a, amount: v });
    }
    if (a.type === "expense") {
      expenses += raw;
      if (raw !== 0) expenseLines.push({ account: a, amount: raw });
    }
  }

  incomeLines.sort((x, y) => y.amount - x.amount);
  expenseLines.sort((x, y) => y.amount - x.amount);

  return { income, expenses, net: income - expenses, incomeLines, expenseLines };
}

export interface TrialBalanceRow {
  account: Account;
  debit: number;
  credit: number;
}

/**
 * Trial balance. Which column an account lands in follows the sign of its
 * balance, not the type of account it is: a positive (net debit) balance is a
 * debit, a negative one is a credit. That is what makes the two totals agree by
 * construction — every entry adds the same amount to one side and the other.
 */
export function computeTrialBalance(
  accounts: Account[],
  balances: Record<string, number>
): { rows: TrialBalanceRow[]; totalDebit: number; totalCredit: number; balanced: boolean } {
  const rows: TrialBalanceRow[] = [];
  let totalDebit = 0;
  let totalCredit = 0;

  for (const a of accounts) {
    const raw = balances[a.id] ?? 0;
    if (Math.abs(raw) < 0.005) continue;
    const debit = Math.max(raw, 0);
    const credit = Math.max(-raw, 0);
    rows.push({ account: a, debit, credit });
    totalDebit += debit;
    totalCredit += credit;
  }

  return {
    rows,
    totalDebit,
    totalCredit,
    balanced: Math.abs(totalDebit - totalCredit) < 0.005,
  };
}

export function topExpenses(
  accounts: Account[],
  balances: Record<string, number>,
  limit = 6
): { account: Account; amount: number }[] {
  return accounts
    .filter((a) => a.type === "expense")
    .map((a) => ({ account: a, amount: balances[a.id] ?? 0 }))
    .filter((e) => e.amount > 0)
    .sort((x, y) => y.amount - x.amount)
    .slice(0, limit);
}

